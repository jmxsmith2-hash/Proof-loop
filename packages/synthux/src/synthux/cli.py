@personas_app.command("generate")
def personas_generate(
    count: int = typer.Option(6, "--count", "-n", help="Number of personas."),
    source: list[Path] = typer.Option([], "--source", "-s", help="Survey/review/notes/analytics files (CSV, JSON, text)."),
    study: Optional[Path] = typer.Option(None, "--study", help="Take count/sources/manual personas from a study file."),
    seed: int = typer.Option(7, help="Seed for the trait spread."),
    config: Optional[Path] = ConfigOpt,
) -> None:
    """Generate personas from your data (anonymized first) with a deliberate trait spread."""
    from synthux.core.llm import LLMGateway
    from synthux.core.study import load_study
    from synthux.personas.generate import PersonaGenerator, save_personas

    s = _settings(config)
    db = _db(s)
    manual, engines, name, include_access = [], [], None, True
    sources = list(source)
    if study:
        st = load_study(study, s)
        count, manual, engines, name = st.personas.count, st.personas.manual, st.personas.engines, st.name
        include_access = st.personas.include_accessibility
        base = Path(st.source_path).parent.parent if st.source_path else Path.cwd()
        sources += [p if Path(p).is_absolute() else base / p for p in st.personas.sources]
    generator = PersonaGenerator(LLMGateway(s, db), seed=seed)
    personas = asyncio.run(generator.generate(count, sources, manual, engines, include_access))
    save_personas(db, personas, study=name)
    for p in personas:
        flag = "  [LOW CONFIDENCE: verify with real users]" if p.low_confidence else ""
        typer.echo(f"{p.id}  {p.label}{flag}")
    if generator.regenerated:
        typer.echo(f"{len(generator.regenerated)} persona(s) regenerated by the diversity check.")


@personas_app.command("list")
def personas_list(study: Optional[str] = typer.Option(None, help="Only personas of this study name."),
                  config: Optional[Path] = ConfigOpt) -> None:
    """List stored personas with their trait values."""
    from synthux.personas.generate import load_personas

    for p in load_personas(_db(_settings(config)), study=study):
        t = p.traits
        typer.echo(f"{p.id}  {p.label}\n    skill={t.tech_skill} patience={t.patience} familiarity={t.familiarity} "
                   f"device={t.device} age={t.age_range} eyesight={t.eyesight} motor={t.motor} mood={t.mood} "
                   f"time_pressure={t.time_pressure}{'  LOW CONFIDENCE' if p.low_confidence else ''}")


