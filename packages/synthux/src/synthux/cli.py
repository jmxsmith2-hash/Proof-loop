log = get_logger(__name__)

app = typer.Typer(help="Synthetic user testing: personas that use your product like people would.",
                  no_args_is_help=True, add_completion=False)
personas_app = typer.Typer(help="Create and inspect personas.", no_args_is_help=True)
physical_app = typer.Typer(help="Predictive feedback on physical products (prediction, not a test).",
                           no_args_is_help=True)
calibrate_app = typer.Typer(help="Compare with real users and tune the simulator.", no_args_is_help=True)
app.add_typer(personas_app, name="personas")
app.add_typer(calibrate_app, name="calibrate")
app.add_typer(physical_app, name="physical")

ConfigOpt = typer.Option(None, "--config", "-c", help="Config directory (default: ./config).")


def _settings(config: Optional[Path]) -> Settings:
    try:
        settings = load_settings(config)
    except ConfigError as exc:
        typer.secho(f"Configuration error: {exc}", fg="red", err=True)
        raise typer.Exit(2)
    setup_logging(settings.log_level)
    return settings


def _smart(settings: Settings, wanted: bool, batch: bool = False) -> Settings:
    if not wanted:
        return settings
    settings, note = settings.smart(batch=batch)
    typer.secho(note, fg="cyan" if "smart mode" in note else "yellow")
    return settings


def _db(settings: Settings) -> Database:
    return Database(settings.db_path)


@app.command()
def check(config: Optional[Path] = ConfigOpt) -> None:
    """Validate settings and show which engines (and costs) are in use."""
    s = _settings(config)
    typer.echo(f"data dir:      {s.data_dir}")
    for role in ("actor", "persona", "judge", "grouper", "reporter"):
        engine, model = s.model_for(role)
        typer.echo(f"{role:9} -> {engine}:{model}")
    typer.echo("allowlist:     " + ", ".join(f"{a.host}:{a.ports or '*'}{' (sandbox)' if a.sandbox else ''}"
                                         for a in s.safety.allowlist))
    _db(s).close()
    typer.secho("settings OK", fg="green")


