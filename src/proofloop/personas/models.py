"""Persona data model with explicit trait values."""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field

AGE_RANGES = ("18-24", "25-34", "35-44", "45-54", "55-64", "65+")
DEVICES = ("desktop", "mobile", "tablet")
EYESIGHT = ("normal", "low_vision", "color_blind")
MOTOR = ("none", "tremor", "limited_dexterity")
MOODS = ("calm", "distracted", "stressed")
BUDGETS = ("tight", "moderate", "generous")
LANGUAGE = ("native", "second_language")
DATE_HABITS = ("MDY", "DMY", "YMD")
STYLES = ("methodical", "scanner", "explorer")  # heuristic-engine analogue of "different models"
HANDS = ("small", "medium", "large")
GRIPS = ("low", "normal", "high")


class Traits(BaseModel):
    tech_skill: int = Field(3, ge=1, le=5)
    patience: int = Field(3, ge=1, le=5)
    familiarity: int = Field(3, ge=1, le=5)      # with similar products
    goal: str = "get the task done"
    budget: Literal["tight", "moderate", "generous"] = "moderate"
    budget_usd: float | None = None
    age_range: Literal["18-24", "25-34", "35-44", "45-54", "55-64", "65+"] = "35-44"
    device: Literal["desktop", "mobile", "tablet"] = "desktop"
    eyesight: Literal["normal", "low_vision", "color_blind"] = "normal"
    motor: Literal["none", "tremor", "limited_dexterity"] = "none"
    mood: Literal["calm", "distracted", "stressed"] = "calm"
    time_pressure: bool = False
    language: Literal["native", "second_language"] = "native"
    date_habit: Literal["MDY", "DMY", "YMD"] = "MDY"
    style: Literal["methodical", "scanner", "explorer"] = "methodical"
    hand_size: Literal["small", "medium", "large"] = "medium"          # physical products
    grip_strength: Literal["low", "normal", "high"] = "normal"

    def sensitive_reasons(self) -> list[str]:
        """Traits whose simulation is unreliable: results must be flagged low confidence."""
        reasons = []
        if self.eyesight != "normal":
            reasons.append(f"eyesight: {self.eyesight}")
        if self.motor != "none":
            reasons.append(f"motor: {self.motor}")
        if self.age_range == "65+":
            reasons.append("age: 65+")
        if self.language != "native":
            reasons.append("language/culture: second language")
        return reasons

    def vector(self) -> list[float]:
        """Numeric embedding of the traits, each dimension scaled to 0..1."""
        return [
            (self.tech_skill - 1) / 4,
            (self.patience - 1) / 4,
            (self.familiarity - 1) / 4,
            AGE_RANGES.index(self.age_range) / (len(AGE_RANGES) - 1),
            DEVICES.index(self.device) / 2,
            0.0 if self.eyesight == "normal" else 1.0,
            0.0 if self.motor == "none" else 1.0,
            MOODS.index(self.mood) / 2,
            1.0 if self.time_pressure else 0.0,
            BUDGETS.index(self.budget) / 2,
            0.0 if self.language == "native" else 1.0,
            STYLES.index(self.style) / 2,
            HANDS.index(self.hand_size) / 2,
            GRIPS.index(self.grip_strength) / 2,
        ]


class Persona(BaseModel):
    id: str
    label: str
    traits: Traits
    narrative: str
    source_summary: str = ""          # which (anonymized) data grounded this persona
    quotes: list[str] = Field(default_factory=list)
    engine: str | None = None         # per-persona engine override
    model: str | None = None          # per-persona model override
    generation: int = 1               # bumped when regenerated by the diversity check

    @property
    def low_confidence(self) -> bool:
        return bool(self.traits.sensitive_reasons())

    @property
    def confidence_note(self) -> str:
        reasons = self.traits.sensitive_reasons()
        if not reasons:
            return ""
        return "Low confidence; verify with real users (" + ", ".join(reasons) + ")."

    def type_label(self) -> str:
        """Short persona-type bucket used for completion-rate tables."""
        skill = {1: "low", 2: "low", 3: "mid", 4: "high", 5: "high"}[self.traits.tech_skill]
        patience = {1: "impatient", 2: "impatient", 3: "steady", 4: "patient", 5: "patient"}[self.traits.patience]
        return f"{skill}-skill / {patience} / {self.traits.device}"
