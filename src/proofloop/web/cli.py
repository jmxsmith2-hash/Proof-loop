@app.command()
def run(
    study: Path = typer.Argument(..., help="Study YAML file."),
    repeats: int | None = typer.Option(None, help="Runs per persona x task (default from settings: 3)."),
    task: list[str] = typer.Option([], "--task", "-t", help="Only these task ids."),
    persona: list[str] = typer.Option([], "--persona", "-p", help="Only these persona ids."),
    dry_run: bool = typer.Option(False, "--dry-run", help="Show the plan and estimated cost, then stop."),
    yes: bool = typer.Option(False, "--yes", "-y", help="Do not ask before a paid run."),
    no_verify: bool = typer.Option(False, "--no-verify", help="Skip judge, replay and questionnaires."),
    profile_name: str | None = typer.Option(None, "--profile", help="Calibration profile version to use."),
    smart: bool = typer.Option(False, "--smart", help="Cheap paid mode for this run if ANTHROPIC_API_KEY is set: "
                                                      "Claude on hard screens and for judging (batched, half price)."),
    config: Path | None = ConfigOpt,
) -> None:
    """Run personas against the study's target (allowlisted URLs only)."""
    from proofloop.personas.generate import PersonaGenerator, load_personas, save_personas
    from proofloop.web.calibration.profiles import load_profile
    from proofloop.web.runner.orchestrator import Orchestrator
    from proofloop.web.safety.allowlist import SafetyError
    from proofloop.web.study import load_study

    s = _smart(_settings(config), smart, batch=True)
    db = _db(s)
    try:
        st = load_study(study, s)
    except (SafetyError, ConfigError) as exc:
        typer.secho(f"Refusing to run: {exc}", fg="red", err=True)
        raise typer.Exit(3) from None
    profile = load_profile(s, db, profile_name)
    people = load_personas(db, ids=persona or st.personas.ids or None, study=None if (persona or st.personas.ids) else st.name)
    if not people:
        typer.echo("No stored personas for this study; generating them now.")
        base = Path(st.source_path).parent.parent if st.source_path else Path.cwd()
        sources = [p if Path(p).is_absolute() else base / p for p in st.personas.sources]
        people = asyncio.run(PersonaGenerator().generate(st.personas.count, sources, st.personas.manual,
                                                         st.personas.engines, st.personas.include_accessibility))
        save_personas(db, people, study=st.name)
    orch = Orchestrator(s, db, st, profile)
    n_sessions = len(people) * (len(task) or len(st.tasks)) * orch.repeats(repeats) * st.visits
    estimate = orch.estimate(people, repeats)
    typer.echo(f"{len(people)} personas x {len(task) or len(st.tasks)} tasks x {orch.repeats(repeats)} repeats"
               f" x {st.visits} visit(s) = {n_sessions} sessions")
    typer.echo(estimate.describe())
    if dry_run:
        raise typer.Exit(0)
    if estimate.total_usd > 0:
        if s.run.max_cost_usd and estimate.total_usd > s.run.max_cost_usd:
            typer.secho(f"Estimated cost ${estimate.total_usd:.2f} exceeds run.max_cost_usd "
                        f"(${s.run.max_cost_usd:.2f}). Lower repeats or raise the limit.", fg="red", err=True)
            raise typer.Exit(4)
        if not yes and not typer.confirm(f"This run will cost about ${estimate.total_usd:.2f}. Continue?"):
            raise typer.Exit(1)

    def progress(result) -> None:
        typer.echo(f"  {result.task_id:14} {result.persona_id:16} rep{result.repeat_index} "
                   f"visit{result.visit_index}: {result.outcome}")

    run_id = asyncio.run(orch.run(people, repeats=repeats, task_ids=task or None, on_session=progress))
    if not no_verify:
        from proofloop.web.judge.pipeline import verify_run

        asyncio.run(verify_run(s, db, st, profile, run_id))
    typer.secho(f"run {run_id} finished. Next: proofloop web report {run_id}", fg="green")


@app.command()
def init(config: Path | None = ConfigOpt) -> None:
    """Answer a few questions to set up a website test (a study file)."""
    import re

    import yaml


    cfg_dir = Path(config) if config else find_config_dir()

    from proofloop.web.safety.allow_edit import add_to_allowlist, host_entry
    from proofloop.web.safety.allowlist import SafetyError, check_url

    url = typer.prompt("Address of the site (a staging or test copy is best)")
    try:
        host, _ = host_entry(url)
    except ConfigError as exc:
        typer.secho(str(exc), fg="red", err=True)
        raise typer.Exit(2) from None
    s = _settings(config)
    try:
        check_url(url, s.safety.allowlist)
    except SafetyError:
        typer.echo(f"{host} is not on the safety allowlist; personas only visit sites listed there.")
        if typer.confirm(f"Add {host} now? (as a real site: payments, emails and deletes stay blocked)", default=True):
            path, _ = add_to_allowlist(cfg_dir, url, note="added by proofloop web init")
            typer.echo(f"Added to {path}.")
        else:
            typer.echo("Not added; add it to config/settings.yaml (safety.allowlist) before running.")
    tasks = []
    while True:
        goal = typer.prompt(f"Task {len(tasks) + 1}: what does a person want to do? (empty to finish)",
                            default="", show_default=False).strip()
        if not goal:
            if tasks:
                break
            typer.echo("Add at least one task.")
            continue
        done = typer.prompt("  What text appears on screen when that is done?")
        find = typer.confirm("  Is it about finding information?", default=goal.lower().startswith(("find", "look")))
        tasks.append({"id": f"task{len(tasks) + 1}", "goal": goal, "start": urlsplit(url).path or "/",
                      "success_text": [done], "type": "find" if find else "do"})
    count = typer.prompt("How many personas?", default=6, type=int)
    parts = urlsplit(url)
    study = {"name": re.sub(r"[^a-z0-9]+", "-", host.lower()).strip("-"),
             "target": {"url": f"{parts.scheme}://{parts.netloc}"}, "tasks": tasks, "personas": {"count": count}}
    out = Path("studies") / f"{study['name']}.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("# Created by `proofloop web init`. See examples/studies/demo.yaml for inputs, keywords, devices and more.\n"
                   + yaml.safe_dump(study, sort_keys=False, allow_unicode=True), encoding="utf-8")
    typer.secho(f"Saved {out}", fg="green")
    typer.echo(f"Next:  proofloop web run {out}      (then: proofloop web report RUN_ID, or open the dashboard)")


@app.command("test")
def quick_test(
    url: str = typer.Argument(..., help="Page where the personas start, e.g. https://staging.example.com/shop"),
    task: list[str] = typer.Option(..., "--task", "-t", help="What a person wants to do there (repeatable)."),
    success: list[str] = typer.Option(..., "--success", "-s",
                                      help="Text that shows the task is done, one per --task, in the same order."),
    find: bool = typer.Option(False, "--find", help="The tasks are about finding information (checks how buried it is)."),
    personas: int = typer.Option(5, "--personas", "-n", help="How many personas."),
    repeats: int = typer.Option(2, help="Runs per persona and task."),
    device: str | None = typer.Option(None, help="desktop, tablet or mobile (default: each persona's own)."),
    allow: bool = typer.Option(False, "--allow", help="Add this site to the allowlist in config/settings.yaml first "
                                                      "(as a real site: payments, emails and deletes stay blocked)."),
    open_report: bool = typer.Option(False, "--open", help="Open the report in the browser when done."),
    yes: bool = typer.Option(False, "--yes", "-y", help="Do not ask before a paid run."),
    smart: bool = typer.Option(False, "--smart", help="Cheap paid mode for this run if ANTHROPIC_API_KEY is set: "
                                                      "Claude on hard screens and for judging."),
    config: Path | None = ConfigOpt,
) -> None:
    """Quick test: personas try one site and you get a report. No study file needed."""
    import webbrowser

    from proofloop.web.quick import build_study, run_quick_test, save_study
    from proofloop.web.safety.allow_edit import add_to_allowlist, host_entry
    from proofloop.web.safety.allowlist import SafetyError, check_url

    if len(success) != len(task):
        typer.secho(f"Give one --success per --task ({len(task)} tasks, {len(success)} --success).", fg="red", err=True)
        raise typer.Exit(2)
    try:
        host, _ = host_entry(url)
    except ConfigError as exc:
        typer.secho(str(exc), fg="red", err=True)
        raise typer.Exit(2) from None
    s = _settings(config)
    try:
        check_url(url, s.safety.allowlist)
    except SafetyError:
        if not allow:
            typer.secho(f"{host} is not on the safety allowlist. Personas only visit sites you list there.\n"
                        f"If this is your own staging or test site, run again with --allow to add it "
                        f"(payments, emails and deletes stay blocked).", fg="red", err=True)
            raise typer.Exit(3) from None
        cfg_dir = Path(config) if config else find_config_dir()
        path, added = add_to_allowlist(cfg_dir, url, note="added by proofloop web test --allow")
        if added:
            typer.echo(f"Added {host} to the allowlist in {path}.")
        s = _settings(config)
    s = _smart(s, smart)
    try:
        st, raw = build_study(s, url, task, success, find=find, personas=personas, repeats=repeats, device=device)
    except (SafetyError, ValueError) as exc:
        typer.secho(f"Refusing to run: {exc}", fg="red", err=True)
        raise typer.Exit(3) from None
    saved = save_study(s, st, raw)
    db = _db(s)
    typer.echo(f"{personas} personas x {len(st.tasks)} task(s) x {repeats} repeats on {st.target.url}")

    def approve(estimate) -> bool:
        typer.echo(estimate.describe())
        return yes or typer.confirm(f"This costs about ${estimate.total_usd:.2f}. Continue?")

    def progress(result) -> None:
        typer.echo(f"  {result.task_id:8} {result.persona_id:16} rep{result.repeat_index}: {result.outcome}")

    try:
        run_id, path, estimate = asyncio.run(run_quick_test(s, db, st, personas=personas, repeats=repeats,
                                                            approve=approve, on_session=progress))
    except ValueError as exc:
        typer.secho(str(exc), fg="red", err=True)
        raise typer.Exit(4) from None
    if run_id is None:
        raise typer.Exit(1)
    if estimate.total_usd == 0:
        typer.echo(estimate.describe())
    typer.secho(f"Report: {path}", fg="green")
    typer.echo(f"This test was saved as {saved}; edit it to add tasks, then `proofloop web run {saved}`.")
    if open_report:
        webbrowser.open(path.resolve().as_uri())


@app.command()
def report(run_id: str = typer.Argument(..., help="Run id (see `proofloop web runs`)."),
           out: Path | None = typer.Option(None, "--out", "-o", help="Output folder (default data/reports/RUN)."),
           config: Path | None = ConfigOpt) -> None:
    """Build the static HTML report for a run."""
    from proofloop.core.llm import LLMGateway
    from proofloop.web.report.build import ReportBuilder

    s = _settings(config)
    db = _db(s)
    path = asyncio.run(ReportBuilder(s, db, LLMGateway(s, db, run_id=run_id)).build(run_id, out))
    typer.echo(SYNTHETIC_DISCLAIMER)
    rows = db.all("SELECT title, screen_id, confidence, score FROM issue_clusters WHERE run_id = ? AND promoted = 1 "
                  "ORDER BY score DESC LIMIT 10", [run_id])
    for n, r in enumerate(rows, 1):
        typer.echo(f"{n:2}. {r['title']} ({r['screen_id']}, {r['confidence']} confidence)")
    typer.secho(f"report: {path}", fg="green")


